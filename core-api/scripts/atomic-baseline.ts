import { join } from "node:path";
import { readText, REPO_ROOT, sha256 } from "./db-lib.ts";

const SCHEMA_FILES = [
  "01_tables",
  "02_functions",
  "03_views",
  "04_triggers",
  "05_policies",
  "06_grants",
  "07_storage",
  "08_search",
];

// The stock postgres image has no "http" extension, and 0004 replaces the only function using it.
const HTTP_EXTENSION = /^create extension if not exists "http".*\n/m;

export const atomicSource = (): string =>
  SCHEMA_FILES.map((name) => readText(join(REPO_ROOT, "backoffice/supabase/schemas", `${name}.sql`))).join("\n");

export const renderBaseline = (): string => {
  const source = atomicSource();
  return [
    "-- GENERATED by core-api/scripts/gen-atomic-baseline.ts. Do not edit.",
    "-- Frozen copy of backoffice/supabase/schemas/01..08, the Atomic CRM schema.",
    `-- source-sha256: ${sha256(source)}`,
    "",
    source.replace(HTTP_EXTENSION, ""),
  ].join("\n");
};

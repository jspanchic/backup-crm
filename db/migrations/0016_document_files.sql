-- PDFs of the numbered documents (CRM-T14b). The database keeps what a file IS (its SHA-256 and size) and
-- which document it belongs to; the bytes live in a private folder of core-api, named after the hash.
-- A file row is never changed or deleted: a new rendering is a new row, and the latest one is the current file.

create table core.document_files (
  id bigint generated by default as identity primary key,
  document_id bigint not null references core.documents (id) on delete restrict,
  template_name text not null,
  template_version text not null,
  sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  size_bytes integer not null check (size_bytes > 0),
  created_at timestamptz not null default now()
);
create index document_files_document_idx on core.document_files (document_id, id desc);

create function core.document_files_guard() returns trigger
  language plpgsql
  set search_path = ''
  as $$
begin
  raise exception 'stored document files cannot be changed or deleted' using errcode = 'CX001';
end;
$$;
create trigger document_files_guard before update or delete on core.document_files
  for each row execute function core.document_files_guard();

-- A queued message may carry a file. The text in `body` is its caption.
alter table core.outbox
  add column document_file_id bigint references core.document_files (id);

-- The live document of a kind: the one of a quote, or the issued one of an appointment.
create function core.find_live_document(p_type text, p_quote_id bigint, p_appointment_id bigint) returns core.documents
  language sql stable
  set search_path = ''
  as $$
    select d.*
    from core.documents d
    where d.document_type = p_type
      and case when p_type = 'quote' then d.quote_id = p_quote_id
               else d.appointment_id = p_appointment_id and d.status = 'issued' end
    limit 1
  $$;

-- Issues the numbered record of a quote, purchase order or work order and returns it. Asking again for
-- the same quote or appointment returns the document that already exists, so a double click or a retry
-- after a failed rendering never burns a number. The amounts come from the quote (see
-- core.documents_before_insert); what is written here is only the description of the job.
create function api.issue_document(p_deal_id bigint, p_document_type text, p_appointment_id bigint default null)
  returns jsonb
  language plpgsql
  security definer
  set search_path = ''
  as $$
declare
  v_deal public.deals;
  v_quote core.quotes;
  v_brand core.brands;
  v_contact public.contacts;
  v_document core.documents;
  v_created boolean := false;
  v_start timestamptz;
  v_end timestamptz;
  v_address text;
  v_technician text;
  v_appointment_deal bigint;
begin
  if p_document_type not in ('quote', 'purchase_order', 'work_order') then
    raise exception 'unknown document type' using errcode = 'CX004', hint = 'invalid_document_type';
  end if;
  if (p_document_type = 'quote') <> (p_appointment_id is null) then
    raise exception 'only orders take an appointment' using errcode = 'CX004', hint = 'appointment_mismatch';
  end if;

  select * into v_deal from public.deals where id = p_deal_id;
  if not found then
    raise exception 'unknown deal' using errcode = 'CX004', hint = 'unknown_deal';
  end if;
  select * into v_quote from core.quotes where deal_id = p_deal_id order by version desc limit 1;
  if not found then
    raise exception 'the deal has no quote yet' using errcode = 'CX002', hint = 'no_quote';
  end if;

  v_document := core.find_live_document(p_document_type, v_quote.id, p_appointment_id);
  if v_document.id is null then
    if p_appointment_id is not null then
      select a.deal_id, a.start_at, a.end_at, a.address, t.name
        into v_appointment_deal, v_start, v_end, v_address, v_technician
      from core.appointments a join core.technicians t on t.id = a.technician_id
      where a.id = p_appointment_id;
      if v_appointment_deal is distinct from p_deal_id then
        raise exception 'the appointment does not belong to this deal' using errcode = 'CX004', hint = 'unknown_appointment';
      end if;
    end if;

    select * into v_brand from core.brands where id = v_deal.brand_id;
    select * into v_contact from public.contacts where id = coalesce(v_deal.primary_contact_id, v_deal.contact_ids[1]);

    begin
      insert into core.documents (document_type, deal_id, quote_id, appointment_id, payload)
      values (
        p_document_type, p_deal_id, v_quote.id, p_appointment_id,
        jsonb_build_object(
          'brand_name', v_brand.name,
          'timezone', v_brand.timezone,
          'customer_name', nullif(btrim(coalesce(v_contact.first_name, '') || ' ' || coalesce(v_contact.last_name, '')), ''),
          'deal_name', v_deal.name,
          'service_space_type', v_deal.service_space_type,
          'service_space_size', v_deal.service_space_size,
          'service_address', coalesce(v_address, v_deal.service_address),
          'quote_valid_until', v_quote.valid_until,
          'appointment_start_at', v_start,
          'appointment_end_at', v_end,
          'technician_name', v_technician
        )
      )
      returning * into v_document;
      v_created := true;
    exception when unique_violation then
      -- Another request issued it between the look-up and the insert.
      v_document := core.find_live_document(p_document_type, v_quote.id, p_appointment_id);
    end;
  end if;

  return jsonb_build_object(
    'id', v_document.id, 'display_number', v_document.display_number, 'document_type', v_document.document_type,
    'is_test', v_document.is_test, 'status', v_document.status, 'created', v_created
  );
end;
$$;

-- Everything the template may show: the document and its frozen payload, nothing from live data.
create function api.document_render_data(p_document_id bigint) returns jsonb
  language sql stable
  security definer
  set search_path = ''
  as $$
    select jsonb_build_object(
      'id', d.id, 'display_number', d.display_number, 'document_type', d.document_type, 'is_test', d.is_test,
      'status', d.status, 'issued_at', d.issued_at, 'payload', d.payload
    )
    from core.documents d where d.id = p_document_id
  $$;

create function api.record_document_file(
  p_document_id bigint, p_template_name text, p_template_version text, p_sha256 text, p_size_bytes integer
) returns bigint
  language sql
  security definer
  set search_path = ''
  as $$
    insert into core.document_files (document_id, template_name, template_version, sha256, size_bytes)
    values (p_document_id, p_template_name, p_template_version, p_sha256, p_size_bytes)
    returning id
  $$;

-- The current file of a document, with what is needed to name and gate it. Null when there is none.
create function api.document_file(p_document_id bigint) returns jsonb
  language sql stable
  security definer
  set search_path = ''
  as $$
    select jsonb_build_object(
      'id', f.id, 'sha256', f.sha256, 'size_bytes', f.size_bytes, 'template_name', f.template_name,
      'template_version', f.template_version, 'created_at', f.created_at,
      'document_id', d.id, 'display_number', d.display_number, 'document_type', d.document_type,
      'is_test', d.is_test, 'status', d.status
    )
    from core.document_files f join core.documents d on d.id = f.document_id
    where f.document_id = p_document_id
    order by f.id desc
    limit 1
  $$;

-- Queues the file for the customer's open conversation. It goes out through the outbox like any other
-- message: same pace, same retries, and the conversation shows what was sent.
create function api.enqueue_document(p_document_id bigint, p_file_id bigint, p_caption text) returns bigint
  language plpgsql
  security definer
  set search_path = ''
  as $$
declare
  v_document core.documents;
  v_contact_id bigint;
  v_conversation core.conversations;
  v_identity core.contact_identities;
  v_outbox_id bigint;
begin
  select * into v_document from core.documents where id = p_document_id;
  if not found or not exists (select 1 from core.document_files where id = p_file_id and document_id = p_document_id) then
    raise exception 'unknown document file' using errcode = 'CX004', hint = 'unknown_document';
  end if;
  if v_document.status <> 'issued' then
    raise exception 'a voided document is not sent' using errcode = 'CX002', hint = 'voided';
  end if;

  select coalesce(
    (select a.contact_id from core.appointments a where a.id = v_document.appointment_id),
    (select coalesce(d.primary_contact_id, d.contact_ids[1]) from public.deals d where d.id = v_document.deal_id)
  ) into v_contact_id;

  select * into v_conversation
  from core.conversations
  where contact_id = v_contact_id and brand_id = v_document.brand_id and closed_at is null and superseded_by is null
  order by opened_at desc limit 1;
  if not found then
    raise exception 'the customer has no open conversation' using errcode = 'CX002', hint = 'no_conversation';
  end if;
  select * into v_identity from core.contact_identities where id = v_conversation.identity_id;

  insert into core.messages (brand_id, conversation_id, channel_id, direction, sender, body, sent_at)
  values (v_conversation.brand_id, v_conversation.id, v_conversation.channel_id, 'out', 'human', p_caption, now());

  insert into core.outbox (brand_id, channel_id, conversation_id, destination, body, document_file_id)
  values (
    v_conversation.brand_id, v_conversation.channel_id, v_conversation.id,
    case v_identity.type when 'phone_e164' then substr(v_identity.value, 2) || '@c.us' else v_identity.value end,
    p_caption, p_file_id
  )
  returning id into v_outbox_id;
  return v_outbox_id;
end;
$$;

-- Same as before, plus the file a row carries. core-api checks the SHA-256 before it sends the bytes.
drop function api.claim_outbox(integer);
create function api.claim_outbox(p_limit integer)
  returns table (id bigint, session text, destination text, body text, attempts integer,
                 document_file_id bigint, file_sha256 text, file_name text)
  language sql
  security definer
  set search_path = ''
  as $$
    with due as (
      select o.id
      from core.outbox o
      where (o.status = 'pending' and o.scheduled_at <= now())
         or (o.status = 'sending' and o.scheduled_at < now() - interval '2 minutes')
      order by o.scheduled_at, o.id
      limit p_limit
      for update skip locked
    ), claimed as (
      update core.outbox o
      set status = 'sending', attempts = o.attempts + 1, scheduled_at = now()
      from due, core.channels c
      where o.id = due.id and c.id = o.channel_id
      returning o.id, c.identifier, o.destination, o.body, o.attempts, o.document_file_id
    )
    select cl.id, cl.identifier, cl.destination, cl.body, cl.attempts,
           cl.document_file_id, f.sha256, d.display_number || '.pdf'
    from claimed cl
    left join core.document_files f on f.id = cl.document_file_id
    left join core.documents d on d.id = f.document_id
    order by cl.id
  $$;

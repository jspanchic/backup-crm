-- Escalate an unresolved LID without creating an identity, contact, or conversation.
create table core.waha_lid_escalations (
  id bigint generated by default as identity primary key,
  channel_id bigint not null references core.channels (id),
  provider_message_id text not null check (length(provider_message_id) between 1 and 300),
  chat_id text not null check (chat_id ~ '^[0-9]+(:[0-9]+)?@lid$' and length(chat_id) <= 200),
  created_at timestamptz not null default now(),
  handled_at timestamptz,
  unique (channel_id, provider_message_id)
);

-- Hash provider IDs after a team reset so retries cannot recreate deleted data.
create table core.team_reset_receipts (
  channel_id bigint not null references core.channels (id),
  provider_message_hash bytea not null check (octet_length(provider_message_hash) = 32),
  primary key (channel_id, provider_message_hash)
);

alter table core.messages drop constraint messages_waha_chat_id_check;
alter table core.messages add constraint messages_waha_chat_id_check check (
  waha_chat_id ~ '^[0-9]{1,200}@(c[.]us|lid)$'
  or (length(waha_chat_id) <= 200 and waha_chat_id ~ '^[0-9]+:[0-9]+@lid$')
);

create function api.escalate_waha_lid(p_channel_id bigint, p_provider_message_id text, p_chat_id text) returns bigint
  language plpgsql
  security definer
  set search_path = ''
  as $$
declare
  v_id bigint;
begin
  if not exists (select 1 from core.channels where id = p_channel_id and provider = 'waha' and active) then
    raise exception 'unknown WAHA channel' using errcode = 'CX004';
  end if;
  perform pg_advisory_xact_lock(hashtext('msg:' || p_channel_id || ':' || p_provider_message_id));
  if exists (
    select 1 from core.messages where channel_id = p_channel_id and provider_message_id = p_provider_message_id
  ) or exists (
    select 1 from core.team_reset_receipts
    where channel_id = p_channel_id and provider_message_hash = sha256(convert_to(p_provider_message_id, 'UTF8'))
  ) then
    return null;
  end if;

  insert into core.waha_lid_escalations (channel_id, provider_message_id, chat_id)
  values (p_channel_id, p_provider_message_id, p_chat_id)
  on conflict (channel_id, provider_message_id) do nothing
  returning id into v_id;
  return v_id;
end;
$$;

-- A delivery already handed to an operator stays there even if a later retry resolves the phone.
create or replace function api.ingest_inbound(
  p_provider text, p_identifier text, p_provider_message_id text, p_sent_at timestamptz,
  p_body text, p_phone_e164 text, p_lid text, p_push_name text, p_waha_chat_id text
) returns jsonb
  language plpgsql
  security definer
  set search_path = ''
  as $$
declare
  v_channel_id bigint;
  v_result jsonb;
begin
  select id into v_channel_id from core.channels where provider = p_provider and identifier = p_identifier and active;
  if v_channel_id is not null then
    perform pg_advisory_xact_lock(hashtext('msg:' || v_channel_id || ':' || p_provider_message_id));
    if exists (
      select 1 from core.waha_lid_escalations where channel_id = v_channel_id and provider_message_id = p_provider_message_id
    ) then
      return jsonb_build_object('status', 'duplicate');
    end if;
  end if;

  v_result := api.ingest_inbound(p_provider, p_identifier, p_provider_message_id, p_sent_at,
                                 p_body, p_phone_e164, p_lid, p_push_name);
  if v_result ->> 'status' = 'accepted' then
    update core.messages set waha_chat_id = p_waha_chat_id where id = (v_result ->> 'message_id')::bigint;
  end if;
  return v_result;
end;
$$;

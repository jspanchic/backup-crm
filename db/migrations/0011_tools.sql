-- Bot tools: everything the bot can do goes through these functions. None of them takes a
-- contact id: the contact comes from the conversation, which comes from the signed token.

alter table core.brands
  add column allowed_reply_domains text[] not null default '{}';

alter table public.deals
  add column client_type text check (client_type in ('home', 'business'));

-- Replies the review stopped, kept to see what the model tried to say.
create table core.reply_reviews (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references core.conversations (id),
  reason text not null,
  body text not null,
  created_at timestamptz not null default now()
);

-- Version with the text that is sent, which may differ from what is kept in the history:
-- the history shows {{telefono}}, the customer receives the number.
drop function api.enqueue_outbound(bigint, text, text);
create function api.enqueue_outbound(
  p_conversation_id bigint,
  p_body text,
  p_sender text default 'bot',
  p_send_body text default null
) returns bigint
  language plpgsql
  security definer
  set search_path = ''
  as $$
declare
  conversation core.conversations;
  identity core.contact_identities;
  v_outbox_id bigint;
begin
  if p_sender not in ('bot', 'human') then
    raise exception 'invalid sender' using errcode = 'CX004';
  end if;
  select * into conversation from core.conversations where id = p_conversation_id;
  if not found then
    raise exception 'unknown conversation' using errcode = 'CX004';
  end if;
  select * into identity from core.contact_identities where id = conversation.identity_id;

  insert into core.messages (brand_id, conversation_id, channel_id, direction, sender, body, sent_at)
  values (conversation.brand_id, conversation.id, conversation.channel_id, 'out', p_sender, p_body, now());

  insert into core.outbox (brand_id, channel_id, conversation_id, destination, body)
  values (
    conversation.brand_id, conversation.channel_id, conversation.id,
    case identity.type when 'phone_e164' then substr(identity.value, 2) || '@c.us' else identity.value end,
    coalesce(p_send_body, p_body)
  )
  returning id into v_outbox_id;
  return v_outbox_id;
end;
$$;

-- What a tool may do for a token: the conversation it names, or the one that replaced it.
-- The brand in the token must be the brand of the conversation.
create function api.tool_conversation(p_conversation_id bigint, p_brand_id bigint) returns jsonb
  language plpgsql stable
  security definer
  set search_path = ''
  as $$
declare
  conversation core.conversations;
  hops integer := 0;
begin
  select * into conversation from core.conversations where id = p_conversation_id;
  if not found or conversation.brand_id <> p_brand_id then
    return null;
  end if;
  while conversation.superseded_by is not null and hops < 5 loop
    select * into conversation from core.conversations where id = conversation.superseded_by;
    hops := hops + 1;
  end loop;
  return jsonb_build_object(
    'conversation_id', conversation.id,
    'bot_paused', conversation.bot_paused,
    'closed', conversation.closed_at is not null
  );
end;
$$;

-- Facts about the conversation's open opportunity. Internal: not callable from outside.
create function core.deal_facts(p_conversation_id bigint) returns jsonb
  language plpgsql stable
  set search_path = ''
  as $$
declare
  conversation core.conversations;
  contact public.contacts;
  brand core.brands;
  deal public.deals;
  price_list core.price_lists;
  quote core.quotes;
  appointment core.appointments;
  v_phone text;
begin
  select * into conversation from core.conversations where id = p_conversation_id;
  select * into contact from public.contacts where id = conversation.contact_id;
  select * into brand from core.brands where id = conversation.brand_id;
  select * into deal from public.deals
    where primary_contact_id = contact.id and stage not in ('won', 'lost') and archived_at is null
    order by id desc limit 1;
  select i.value into v_phone from core.contact_identities i
    where i.id = conversation.identity_id and i.type = 'phone_e164';

  select * into quote from core.quotes where deal_id = deal.id and status = 'sent' order by version desc limit 1;
  select * into price_list from core.price_lists
    where id = coalesce(quote.price_list_id, core.active_price_list(brand.id));
  select * into appointment from core.appointments
    where deal_id = deal.id and status in ('hold', 'confirmed')
    order by (status = 'confirmed') desc, start_at limit 1;

  return jsonb_build_object(
    'brand_id', brand.id,
    'timezone', brand.timezone,
    'allowed_reply_domains', to_jsonb(brand.allowed_reply_domains),
    'phone_e164', v_phone,
    'deal_id', deal.id,
    'stage', deal.stage,
    'client_type', deal.client_type,
    'zip', deal.zip,
    'address', deal.service_address,
    'space_type', deal.service_space_type,
    'space_size', deal.service_space_size,
    'currency', price_list.currency,
    'rates', case when price_list.id is null then null else jsonb_build_object(
      'covered', price_list.covered_rate,
      'uncovered', price_list.uncovered_rate,
      'discount_pct', price_list.discount_pct,
      'min_total', price_list.min_total,
      'confirmed', price_list.is_confirmed
    ) end,
    'quote', case when quote.id is null then null else jsonb_build_object(
      'version', quote.version,
      'covered_sqft', quote.covered_sqft,
      'uncovered_sqft', quote.uncovered_sqft,
      'subtotal', quote.subtotal,
      'discount', quote.discount,
      'total', quote.total,
      'min_applied', quote.min_applied,
      'price_confirmed', quote.price_confirmed,
      'covered_cost', round(quote.covered_sqft * price_list.covered_rate, 2),
      'uncovered_cost', round(quote.uncovered_sqft * price_list.uncovered_rate, 2)
    ) end,
    'appointment', case when appointment.id is null then null else jsonb_build_object(
      'status', appointment.status,
      'start_at', appointment.start_at,
      'end_at', appointment.end_at,
      'address', appointment.address,
      'hold_expires_at', appointment.hold_expires_at
    ) end
  );
end;
$$;

-- `ficha`: what the bot may know about this customer. Never the full phone number.
create function api.contact_card(p_conversation_id bigint) returns jsonb
  language plpgsql stable
  security definer
  set search_path = ''
  as $$
declare
  conversation core.conversations;
  contact public.contacts;
  facts jsonb := core.deal_facts(p_conversation_id);
  v_phone text := facts ->> 'phone_e164';
begin
  select * into conversation from core.conversations where id = p_conversation_id;
  select * into contact from public.contacts where id = conversation.contact_id;
  return jsonb_build_object(
    'nombre', case when contact.first_name = 'WhatsApp' then null else contact.first_name end,
    'apellido', case when contact.last_name like '••%' then null else contact.last_name end,
    'email', contact.email_jsonb -> 0 ->> 'email',
    'idioma', contact.preferred_language,
    'telefono_enmascarado', case when v_phone is not null
      then left(v_phone, 2) || repeat('•', greatest(length(v_phone) - 6, 1)) || right(v_phone, 4) end,
    'etapa', facts -> 'stage',
    'tipo_cliente', facts -> 'client_type',
    'tipo_espacio', facts -> 'space_type',
    'direccion', facts -> 'address',
    'tamano', facts -> 'space_size',
    'zip', facts -> 'zip',
    'cotizacion_vigente', facts -> 'quote',
    'cita', facts -> 'appointment'
  );
end;
$$;

-- `guardar_datos`: only the keys that come in are changed, and only after validation.
create function api.save_contact_data(p_conversation_id bigint, p_data jsonb) returns jsonb
  language plpgsql
  security definer
  set search_path = ''
  as $$
declare
  conversation core.conversations;
  contact public.contacts;
  v_deal_id bigint := (core.deal_facts(p_conversation_id) ->> 'deal_id')::bigint;
  v_first text;
  v_last text;
  v_email text;
  v_changed text[] := '{}';
begin
  select * into conversation from core.conversations where id = p_conversation_id for update;
  select * into contact from public.contacts where id = conversation.contact_id for update;

  if p_data ? 'first_name' or p_data ? 'last_name' then
    v_first := coalesce(nullif(trim(p_data ->> 'first_name'), ''), contact.first_name);
    v_last := coalesce(nullif(trim(p_data ->> 'last_name'), ''), contact.last_name);
    if p_data ? 'first_name' and not p_data ? 'last_name' and position(' ' in v_first) > 0 and contact.last_name like '••%' then
      -- "Carlos Pérez" in one field: the first word is the name, the rest the surname.
      v_last := substr(v_first, position(' ' in v_first) + 1);
      v_first := split_part(v_first, ' ', 1);
    end if;
    if length(v_first) > 80 or length(v_last) > 80 then
      raise exception 'name too long' using errcode = 'CX004';
    end if;
    update public.contacts set first_name = v_first, last_name = v_last where id = contact.id;
    v_changed := array_append(v_changed, 'nombre');
  end if;

  if p_data ? 'email' then
    v_email := lower(trim(p_data ->> 'email'));
    if v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' or length(v_email) > 200 then
      raise exception 'invalid email' using errcode = 'CX004';
    end if;
    if not coalesce(contact.email_jsonb, '[]'::jsonb) @> jsonb_build_array(jsonb_build_object('email', v_email)) then
      update public.contacts
      set email_jsonb = coalesce(email_jsonb, '[]'::jsonb) || jsonb_build_array(jsonb_build_object('email', v_email, 'type', 'Work'))
      where id = contact.id;
    end if;
    v_changed := array_append(v_changed, 'email');
  end if;

  if p_data ? 'language' then
    if p_data ->> 'language' not in ('es', 'en') then
      raise exception 'invalid language' using errcode = 'CX004';
    end if;
    update public.contacts set preferred_language = p_data ->> 'language' where id = contact.id;
    v_changed := array_append(v_changed, 'idioma');
  end if;

  if v_deal_id is not null then
    if p_data ? 'client_type' then
      if p_data ->> 'client_type' not in ('home', 'business') then
        raise exception 'invalid client type' using errcode = 'CX004';
      end if;
      update public.deals set client_type = p_data ->> 'client_type' where id = v_deal_id;
      v_changed := array_append(v_changed, 'tipo_cliente');
    end if;
    if p_data ? 'space_type' then
      if p_data ->> 'space_type' not in (
        'home', 'office_warehouse', 'restaurant_kitchen', 'clinic', 'veterinary', 'gym', 'school_daycare', 'hotel_rental', 'other'
      ) then
        raise exception 'invalid space type' using errcode = 'CX004';
      end if;
      update public.deals set service_space_type = p_data ->> 'space_type' where id = v_deal_id;
      v_changed := array_append(v_changed, 'tipo_espacio');
    end if;
    if p_data ? 'address' then
      if length(p_data ->> 'address') > 300 then
        raise exception 'address too long' using errcode = 'CX004';
      end if;
      update public.deals set service_address = nullif(trim(p_data ->> 'address'), '') where id = v_deal_id;
      v_changed := array_append(v_changed, 'direccion');
    end if;
    if p_data ? 'space_size' then
      if length(p_data ->> 'space_size') > 100 then
        raise exception 'size too long' using errcode = 'CX004';
      end if;
      update public.deals set service_space_size = nullif(trim(p_data ->> 'space_size'), '') where id = v_deal_id;
      v_changed := array_append(v_changed, 'tamano');
    end if;
    if p_data ? 'zip' then
      if (p_data ->> 'zip') !~ '^[A-Za-z0-9][A-Za-z0-9 -]{1,8}[A-Za-z0-9]$' then
        raise exception 'invalid zip' using errcode = 'CX004';
      end if;
      update public.deals set zip = upper(trim(p_data ->> 'zip')) where id = v_deal_id;
      v_changed := array_append(v_changed, 'zip');
    end if;
    -- First name and type of customer move the opportunity out of "new inquiry".
    update public.deals set stage = 'contacted'
    where id = v_deal_id and stage = 'opportunity' and client_type is not null
      and exists (select 1 from public.contacts c where c.id = contact.id and c.first_name <> 'WhatsApp');
  elsif p_data ?| array['client_type', 'space_type', 'address', 'space_size', 'zip'] then
    raise exception 'no open opportunity' using errcode = 'CX002';
  end if;

  return jsonb_build_object('guardado', to_jsonb(v_changed));
end;
$$;

-- `cotizar`: the model sends what the customer said; every amount is calculated here.
create function api.create_quote(p_conversation_id bigint, p_inputs jsonb) returns jsonb
  language plpgsql
  security definer
  set search_path = ''
  as $$
declare
  facts jsonb := core.deal_facts(p_conversation_id);
  v_deal_id bigint := (facts ->> 'deal_id')::bigint;
  v_price_list_id bigint;
  area record;
  v_quote core.quotes;
begin
  if v_deal_id is null then
    raise exception 'no open opportunity' using errcode = 'CX002';
  end if;
  v_price_list_id := core.active_price_list((facts ->> 'brand_id')::bigint);
  if v_price_list_id is null then
    raise exception 'no price list in force' using errcode = 'CX004';
  end if;

  select * into area from core.quote_area(v_price_list_id, p_inputs);

  update core.quotes set status = 'superseded' where deal_id = v_deal_id and status = 'sent';
  insert into core.quotes (deal_id, price_list_id, covered_sqft, uncovered_sqft, inputs)
  values (v_deal_id, v_price_list_id, area.covered_sqft, area.uncovered_sqft, p_inputs)
  returning * into v_quote;

  update public.deals
  set amount = v_quote.total,
      client_type = coalesce(client_type, p_inputs ->> 'client_type'),
      stage = case when stage in ('opportunity', 'contacted', 'assessment') then 'proposal-sent' else stage end,
      updated_at = now()
  where id = v_deal_id;

  return core.deal_facts(p_conversation_id) -> 'quote'
    || jsonb_build_object('currency', v_quote.currency, 'discount_pct', facts -> 'rates' -> 'discount_pct');
end;
$$;

-- `escalar`: pauses the bot for this conversation and leaves a task for a person.
create function api.escalate(p_conversation_id bigint, p_reason text) returns jsonb
  language plpgsql
  security definer
  set search_path = ''
  as $$
declare
  conversation core.conversations;
  brand core.brands;
  contact public.contacts;
begin
  select * into conversation from core.conversations where id = p_conversation_id for update;
  if conversation.bot_paused then
    return jsonb_build_object('pausado', true, 'ya_estaba_pausado', true);
  end if;
  select * into brand from core.brands where id = conversation.brand_id;
  select * into contact from public.contacts where id = conversation.contact_id;

  update core.conversations
  set bot_paused = true, bot_paused_at = now(), bot_paused_reason = left(p_reason, 300)
  where id = conversation.id;

  insert into public.tasks (contact_id, type, text, due_date, sales_id)
  values (contact.id, 'follow-up', 'Atender a mano: el bot pidió ayuda. Motivo: ' || left(p_reason, 300), now(), brand.default_sales_id);

  return jsonb_build_object('pausado', true, 'ya_estaba_pausado', false);
end;
$$;

-- What `responder` compares the model's text against. Includes the phone, which only core-api sees.
create function api.reply_facts(p_conversation_id bigint) returns jsonb
  language sql stable
  security definer
  set search_path = ''
  as $$ select core.deal_facts(p_conversation_id) $$;

create function api.record_reply_review(p_conversation_id bigint, p_reason text, p_body text) returns void
  language sql
  security definer
  set search_path = ''
  as $$ insert into core.reply_reviews (conversation_id, reason, body) values (p_conversation_id, left(p_reason, 100), left(p_body, 4000)) $$;

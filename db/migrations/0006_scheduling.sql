-- Technicians, availability and appointments. The no-overlap rule lives here, not in the app.

create table core.scheduling_settings (
  brand_id bigint primary key references core.brands (id),
  slot_minutes integer not null check (slot_minutes > 0),
  buffer_minutes integer not null check (buffer_minutes >= 0),
  hold_minutes integer not null check (hold_minutes > 0),
  min_notice_minutes integer not null check (min_notice_minutes >= 0),
  horizon_days integer not null check (horizon_days > 0),
  reverify_after_days integer not null check (reverify_after_days > 0),
  is_confirmed boolean not null default false, -- false = "por confirmar" with JM
  updated_at timestamptz not null default now()
);

create table core.technicians (
  id bigint generated by default as identity primary key,
  brand_id bigint not null references core.brands (id),
  name text not null,
  phone_e164 text check (phone_e164 ~ '^\+[1-9][0-9]{7,14}$'),
  sales_id bigint references public.sales (id),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Whitelist: a time that is not here is never offered.
create table core.technician_availability (
  id bigint generated by default as identity primary key,
  technician_id bigint not null references core.technicians (id),
  weekday smallint not null check (weekday between 0 and 6), -- 0 = Sunday
  start_time time not null,
  end_time time not null,
  created_at timestamptz not null default now(),
  check (end_time > start_time)
);
create index technician_availability_idx on core.technician_availability (technician_id, weekday);

create table core.technician_time_off (
  id bigint generated by default as identity primary key,
  technician_id bigint not null references core.technicians (id),
  period tstzrange not null check (not isempty(period)),
  reason text,
  created_at timestamptz not null default now()
);
create index technician_time_off_idx on core.technician_time_off using gist (technician_id, period);

create table core.appointments (
  id bigint generated by default as identity primary key,
  brand_id bigint not null references core.brands (id),
  deal_id bigint not null references public.deals (id) on delete restrict,
  contact_id bigint not null references public.contacts (id) on delete restrict,
  technician_id bigint not null references core.technicians (id),
  start_at timestamptz not null,
  end_at timestamptz not null,
  -- End plus the margin, stored at booking time: timestamptz + interval is not immutable, so it
  -- cannot be computed inside the exclusion. Changing the margin later does not touch existing rows.
  blocked_until timestamptz not null,
  status text not null default 'hold'
    check (status in ('hold', 'confirmed', 'done', 'cancelled', 'no_show', 'expired')),
  hold_expires_at timestamptz,
  address text,
  is_test boolean not null default false,
  confirmed_at timestamptz,
  released_at timestamptz,
  created_at timestamptz not null default now(),
  check (end_at > start_at),
  check (blocked_until >= end_at),
  check ((status = 'hold') = (hold_expires_at is not null))
);

-- The condition cannot use now(), so a hold past its time still blocks until it is marked 'expired'.
-- The booking function marks expired holds in its own transaction before inserting.
alter table core.appointments
  add constraint appointments_no_overlap
  exclude using gist (
    technician_id with =,
    tstzrange(start_at, blocked_until, '[)') with &&
  )
  where (status not in ('cancelled', 'expired') and not is_test);

create unique index appointments_one_active_hold_per_contact
  on core.appointments (contact_id)
  where status = 'hold';

create index appointments_deal_idx on core.appointments (deal_id);

-- Everything the caller could use to get around the rules is decided here instead:
-- is_test, the margin, the hold expiry, and the link between deal and contact.
create function core.appointments_before_insert() returns trigger
  language plpgsql
  set search_path = ''
  as $$
declare
  deal public.deals;
  settings core.scheduling_settings;
  technician_brand_id bigint;
begin
  if new.status <> 'hold' then
    raise exception 'an appointment starts as a hold' using errcode = 'CX002';
  end if;

  select * into deal from public.deals where id = new.deal_id;
  if not found then
    raise exception 'unknown deal %', new.deal_id using errcode = 'CX004';
  end if;
  if deal.primary_contact_id is distinct from new.contact_id then
    raise exception 'the contact is not the primary contact of the deal' using errcode = 'CX004';
  end if;

  select brand_id into technician_brand_id from core.technicians where id = new.technician_id and active;
  if technician_brand_id is distinct from deal.brand_id then
    raise exception 'technician not available for this brand' using errcode = 'CX004';
  end if;

  select * into settings from core.scheduling_settings where brand_id = deal.brand_id;
  if not found then
    raise exception 'no scheduling settings for this brand' using errcode = 'CX004';
  end if;

  new.brand_id := deal.brand_id;
  new.is_test := deal.is_test;
  new.blocked_until := new.end_at + make_interval(mins => settings.buffer_minutes);
  new.hold_expires_at := coalesce(new.hold_expires_at, now() + make_interval(mins => settings.hold_minutes));
  new.confirmed_at := null;
  new.released_at := null;
  return new;
end;
$$;
create trigger appointments_before_insert before insert on core.appointments
  for each row execute function core.appointments_before_insert();

-- Valid states: hold -> confirmed | cancelled | expired; confirmed -> done | cancelled | no_show.
-- An expired hold can never be confirmed, whatever the application does.
create function core.appointments_before_update() returns trigger
  language plpgsql
  set search_path = ''
  as $$
begin
  if (new.brand_id, new.deal_id, new.contact_id, new.technician_id, new.start_at, new.end_at, new.blocked_until)
     is distinct from
     (old.brand_id, old.deal_id, old.contact_id, old.technician_id, old.start_at, old.end_at, old.blocked_until) then
    raise exception 'an appointment cannot be moved; cancel it and book again' using errcode = 'CX001';
  end if;

  if new.status = old.status then
    if new.status = 'hold' and new.hold_expires_at is distinct from old.hold_expires_at then
      raise exception 'a hold cannot be extended' using errcode = 'CX002';
    end if;
    return new;
  end if;

  case
    when old.status = 'hold' and new.status = 'confirmed' then
      if old.hold_expires_at <= now() then
        raise exception 'hold expired' using errcode = 'CX003';
      end if;
      new.confirmed_at := now();
      new.hold_expires_at := null;
    when old.status = 'hold' and new.status = 'expired' then
      if old.hold_expires_at > now() then
        raise exception 'hold has not expired yet' using errcode = 'CX002';
      end if;
      new.released_at := now();
      new.hold_expires_at := null;
    when old.status = 'hold' and new.status = 'cancelled' then
      new.released_at := now();
      new.hold_expires_at := null;
    when old.status = 'confirmed' and new.status in ('done', 'no_show') then
      null;
    when old.status = 'confirmed' and new.status = 'cancelled' then
      new.released_at := now();
    else
      raise exception 'invalid status change: % to %', old.status, new.status using errcode = 'CX002';
  end case;
  return new;
end;
$$;
create trigger appointments_before_update before update on core.appointments
  for each row execute function core.appointments_before_update();

create function core.appointments_no_delete() returns trigger
  language plpgsql
  set search_path = ''
  as $$
begin
  raise exception 'appointments cannot be deleted; cancel them' using errcode = 'CX001';
end;
$$;
create trigger appointments_no_delete before delete on core.appointments
  for each row execute function core.appointments_no_delete();

-- Read-only list for the panel. security_invoker stays off on purpose: crm_api reads this
-- view without getting access to schema core.
create view public.appointments_summary as
select
  a.id,
  a.deal_id,
  d.name as deal_name,
  a.contact_id,
  c.first_name,
  c.last_name,
  a.technician_id,
  t.name as technician_name,
  a.start_at,
  a.end_at,
  a.status,
  a.hold_expires_at,
  a.address,
  a.is_test
from core.appointments a
join public.deals d on d.id = a.deal_id
join public.contacts c on c.id = a.contact_id
join core.technicians t on t.id = a.technician_id;

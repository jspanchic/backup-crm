create table core.channels (
  id bigint generated by default as identity primary key,
  brand_id bigint not null references core.brands (id),
  provider text not null check (provider in ('waha')),
  identifier text not null,
  bot_key text not null,
  secret_ref text not null, -- NAME of the environment variable holding the HMAC key, never the key
  is_test boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (provider, identifier)
);

-- Messages from unknown channels: recorded, never sent to a bot. No body and no phone on purpose.
create table core.unrouted_events (
  id bigint generated by default as identity primary key,
  provider text not null,
  identifier text not null,
  received_at timestamptz not null default now()
);

create table core.contact_identities (
  id bigint generated by default as identity primary key,
  brand_id bigint not null references core.brands (id),
  type text not null check (type in ('phone_e164', 'wa_lid')),
  value text not null,
  last_inbound_at timestamptz,
  last_verified_at timestamptz,
  created_at timestamptz not null default now(),
  unique (brand_id, type, value),
  check (type <> 'phone_e164' or value ~ '^\+[1-9][0-9]{7,14}$')
);

-- The holder of an identity is a period: a phone number can change owner without losing history.
create table core.identity_holders (
  id bigint generated by default as identity primary key,
  identity_id bigint not null references core.contact_identities (id),
  contact_id bigint not null references public.contacts (id) on delete restrict,
  valid_from timestamptz not null default now(),
  valid_to timestamptz,
  closed_reason text check (closed_reason in ('reassigned_confirmed', 'merged', 'manual')),
  created_at timestamptz not null default now(),
  check (valid_to is null or valid_to > valid_from),
  check ((valid_to is null) = (closed_reason is null)),
  constraint identity_holders_no_overlap exclude using gist (
    identity_id with =,
    tstzrange(valid_from, coalesce(valid_to, 'infinity'::timestamptz), '[)') with &&
  )
);
create unique index identity_holders_one_open on core.identity_holders (identity_id) where valid_to is null;
create index identity_holders_contact_idx on core.identity_holders (contact_id);

create table core.conversations (
  id bigint generated by default as identity primary key,
  brand_id bigint not null references core.brands (id),
  channel_id bigint not null references core.channels (id),
  identity_id bigint not null references core.contact_identities (id),
  contact_id bigint not null references public.contacts (id) on delete restrict,
  opened_at timestamptz not null default now(),
  closed_at timestamptz,
  closed_reason text,
  -- Set when a number is reassigned: a live token for the old conversation acts on this one instead.
  superseded_by bigint references core.conversations (id),
  bot_paused boolean not null default false,
  bot_paused_at timestamptz,
  bot_paused_reason text,
  legacy_mem_key text,
  created_at timestamptz not null default now(),
  check ((closed_at is null) = (closed_reason is null))
);
create unique index conversations_one_open on core.conversations (channel_id, identity_id) where closed_at is null;
create index conversations_contact_idx on core.conversations (contact_id);

create table core.messages (
  id bigint generated by default as identity primary key,
  brand_id bigint not null references core.brands (id),
  conversation_id bigint not null references core.conversations (id),
  channel_id bigint not null references core.channels (id),
  direction text not null check (direction in ('in', 'out')),
  sender text not null check (sender in ('client', 'bot', 'human')),
  body text not null, -- already redacted by core-api
  provider_message_id text,
  sent_at timestamptz not null,
  bot_dispatched_at timestamptz,
  imported boolean not null default false,
  created_at timestamptz not null default now()
);
-- This index is what drops duplicate webhooks.
create unique index messages_dedupe on core.messages (channel_id, provider_message_id)
  where provider_message_id is not null;
create index messages_conversation_idx on core.messages (conversation_id, sent_at);

create table core.outbox (
  id bigint generated by default as identity primary key,
  brand_id bigint not null references core.brands (id),
  channel_id bigint not null references core.channels (id),
  conversation_id bigint references core.conversations (id),
  destination text not null,
  body text not null,
  status text not null default 'pending' check (status in ('pending', 'sending', 'sent', 'failed')),
  scheduled_at timestamptz not null default now(),
  attempts integer not null default 0 check (attempts >= 0),
  sent_at timestamptz,
  last_error text,
  created_at timestamptz not null default now()
);
create index outbox_due_idx on core.outbox (scheduled_at) where status = 'pending';

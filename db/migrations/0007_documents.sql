-- Quotes, purchase orders and work orders as numbered, immutable records tied to a deal.
-- The PDFs come later (CRM-T14). `payload` is the frozen data a document was issued with,
-- so a PDF rendered at any time shows what the customer was told.

create table core.document_counters (
  brand_id bigint not null references core.brands (id),
  document_type text not null check (document_type in ('quote', 'purchase_order', 'work_order')),
  is_test boolean not null, -- test leads use their own series and never leave gaps in the real one
  prefix text not null,
  last_number bigint not null default 0 check (last_number >= 0),
  primary key (brand_id, document_type, is_test)
);

-- The starting numbers are a business decision: JM can set last_number before going live.
insert into core.document_counters (brand_id, document_type, is_test, prefix) values
  (1, 'quote', false, 'COT'),
  (1, 'purchase_order', false, 'OC'),
  (1, 'work_order', false, 'OT'),
  (1, 'quote', true, 'PRUEBA-COT'),
  (1, 'purchase_order', true, 'PRUEBA-OC'),
  (1, 'work_order', true, 'PRUEBA-OT');

create table core.documents (
  id bigint generated by default as identity primary key,
  brand_id bigint not null references core.brands (id),
  document_type text not null check (document_type in ('quote', 'purchase_order', 'work_order')),
  is_test boolean not null,
  number bigint not null,
  display_number text not null,
  deal_id bigint not null references public.deals (id) on delete restrict,
  quote_id bigint not null references core.quotes (id),
  appointment_id bigint references core.appointments (id),
  replaces_document_id bigint references core.documents (id),
  payload jsonb not null check (jsonb_typeof(payload) = 'object'),
  status text not null default 'issued' check (status in ('issued', 'voided')),
  issued_at timestamptz not null default now(),
  voided_at timestamptz,
  void_reason text,
  unique (brand_id, document_type, is_test, number),
  check ((document_type = 'quote') = (appointment_id is null)),
  check ((status = 'voided') = (voided_at is not null)),
  check ((status = 'voided') = (void_reason is not null))
);

-- One quote document per quote; one live purchase and work order per appointment.
create unique index documents_one_per_quote on core.documents (quote_id)
  where document_type = 'quote';
create unique index documents_one_live_per_appointment on core.documents (appointment_id, document_type)
  where appointment_id is not null and status = 'issued';
create index documents_deal_idx on core.documents (deal_id);

-- The number comes from a counter row, not a sequence: a rolled-back issue leaves no gap,
-- which a sequence cannot promise. The row lock serializes concurrent issues per series.
create function core.documents_before_insert() returns trigger
  language plpgsql
  set search_path = ''
  as $$
declare
  deal public.deals;
  quote core.quotes;
  appointment core.appointments;
  counter core.document_counters;
begin
  select * into deal from public.deals where id = new.deal_id;
  if not found then
    raise exception 'unknown deal %', new.deal_id using errcode = 'CX004';
  end if;

  select * into quote from core.quotes where id = new.quote_id;
  if not found or quote.deal_id <> new.deal_id then
    raise exception 'the quote does not belong to this deal' using errcode = 'CX004';
  end if;

  if new.document_type <> 'quote' then
    select * into appointment from core.appointments where id = new.appointment_id;
    if not found or appointment.deal_id <> new.deal_id then
      raise exception 'the appointment does not belong to this deal' using errcode = 'CX004';
    end if;
    -- The purchase order goes out for the customer to confirm, so a live hold is enough.
    -- A work order sends a technician, so it needs a confirmed appointment.
    if new.document_type = 'purchase_order' and appointment.status not in ('hold', 'confirmed') then
      raise exception 'a purchase order needs a held or confirmed appointment' using errcode = 'CX002';
    end if;
    if new.document_type = 'work_order' and appointment.status <> 'confirmed' then
      raise exception 'a work order needs a confirmed appointment' using errcode = 'CX002';
    end if;
  end if;

  new.brand_id := deal.brand_id;
  new.is_test := deal.is_test;

  update core.document_counters
  set last_number = last_number + 1
  where brand_id = new.brand_id and document_type = new.document_type and is_test = new.is_test
  returning * into counter;
  if not found then
    raise exception 'no document counter for this brand' using errcode = 'CX004';
  end if;

  new.number := counter.last_number;
  new.display_number := counter.prefix || '-' || lpad(counter.last_number::text, 6, '0');
  new.status := 'issued';
  new.issued_at := now();
  new.voided_at := null;
  new.void_reason := null;
  return new;
end;
$$;
create trigger documents_before_insert before insert on core.documents
  for each row execute function core.documents_before_insert();

-- The only change an issued document allows is being voided, once, with a reason.
create function core.documents_guard() returns trigger
  language plpgsql
  set search_path = ''
  as $$
begin
  if tg_op = 'DELETE' then
    raise exception 'documents cannot be deleted; void them' using errcode = 'CX001';
  end if;
  if (to_jsonb(new) - 'status' - 'voided_at' - 'void_reason')
     is distinct from (to_jsonb(old) - 'status' - 'voided_at' - 'void_reason') then
    raise exception 'documents are immutable' using errcode = 'CX001';
  end if;
  if old.status = 'voided' then
    raise exception 'a voided document cannot change' using errcode = 'CX001';
  end if;
  return new;
end;
$$;
create trigger documents_guard before update or delete on core.documents
  for each row execute function core.documents_guard();

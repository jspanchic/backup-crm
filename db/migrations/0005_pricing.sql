-- Versioned prices and immutable quotes. No price lives in code: every amount is derived here.
-- Custom SQLSTATEs: CX001 = immutable data, CX002 = invalid state change, CX003 = hold expired,
-- CX004 = invalid input or inconsistent references.

create table core.price_lists (
  id bigint generated by default as identity primary key,
  brand_id bigint not null references core.brands (id),
  version integer not null check (version > 0),
  valid_from timestamptz not null,
  valid_to timestamptz,
  is_confirmed boolean not null default false, -- false = "por confirmar" with JM
  currency text not null check (currency ~ '^[A-Z]{3}$'),
  covered_rate numeric(10, 4) not null check (covered_rate >= 0),
  uncovered_rate numeric(10, 4) not null check (uncovered_rate >= 0),
  discount_pct numeric(5, 2) not null check (discount_pct between 0 and 100),
  min_total numeric(10, 2) not null check (min_total >= 0),
  home_base_sqft numeric(10, 2) not null check (home_base_sqft >= 0),
  home_bedroom_sqft numeric(10, 2) not null check (home_bedroom_sqft >= 0),
  parking_first_car_sqft numeric(10, 2) not null check (parking_first_car_sqft >= 0),
  parking_extra_car_sqft numeric(10, 2) not null check (parking_extra_car_sqft >= 0),
  sqm_to_sqft numeric(10, 4) not null check (sqm_to_sqft > 0),
  pace_to_ft numeric(10, 4) not null check (pace_to_ft > 0),
  notes text,
  created_at timestamptz not null default now(),
  unique (brand_id, version),
  check (valid_to is null or valid_to > valid_from),
  constraint price_lists_no_overlap exclude using gist (
    brand_id with =,
    tstzrange(valid_from, coalesce(valid_to, 'infinity'::timestamptz), '[)') with &&
  )
);

-- A new price is a new version: only the closing date and the confirmation flag may change.
create function core.price_lists_guard() returns trigger
  language plpgsql
  set search_path = ''
  as $$
begin
  if tg_op = 'DELETE' then
    raise exception 'price lists cannot be deleted' using errcode = 'CX001';
  end if;
  if (to_jsonb(new) - 'valid_to' - 'is_confirmed') is distinct from (to_jsonb(old) - 'valid_to' - 'is_confirmed') then
    raise exception 'price list values are immutable; create a new version' using errcode = 'CX001';
  end if;
  return new;
end;
$$;
create trigger price_lists_guard before update or delete on core.price_lists
  for each row execute function core.price_lists_guard();

create function core.active_price_list(p_brand_id bigint, p_at timestamptz default now()) returns bigint
  language sql stable
  set search_path = ''
  as $$
    select id from core.price_lists
    where brand_id = p_brand_id and valid_from <= p_at and (valid_to is null or valid_to > p_at)
  $$;

-- Rule from the sales prompt: subtotal by covered and uncovered area, minus the discount,
-- rounded to the dollar; if that is below the minimum, the minimum applies.
create function core.quote_totals(
  p_price_list_id bigint,
  p_covered_sqft numeric,
  p_uncovered_sqft numeric,
  out subtotal numeric,
  out discount numeric,
  out total numeric,
  out min_applied boolean
)
  language plpgsql stable
  set search_path = ''
  as $$
declare
  pl core.price_lists;
  raw_subtotal numeric;
  raw_discount numeric;
begin
  select * into pl from core.price_lists where id = p_price_list_id;
  if not found then
    raise exception 'unknown price list %', p_price_list_id using errcode = 'CX004';
  end if;
  if p_covered_sqft < 0 or p_uncovered_sqft < 0 then
    raise exception 'area cannot be negative' using errcode = 'CX004';
  end if;

  raw_subtotal := p_covered_sqft * pl.covered_rate + p_uncovered_sqft * pl.uncovered_rate;
  raw_discount := raw_subtotal * pl.discount_pct / 100;

  subtotal := round(raw_subtotal, 2);
  discount := round(raw_discount, 2);
  total := round(raw_subtotal - raw_discount, 0);
  min_applied := total < pl.min_total;
  if min_applied then
    total := pl.min_total;
  end if;
end;
$$;

-- Turns what the customer said into covered and uncovered area, using the price list parameters.
create function core.quote_area(
  p_price_list_id bigint,
  p_inputs jsonb,
  out covered_sqft numeric,
  out uncovered_sqft numeric
)
  language plpgsql stable
  set search_path = ''
  as $$
declare
  pl core.price_lists;
  area jsonb;
  area_sqft numeric;
  client_type text := p_inputs ->> 'client_type';

  -- 240 for the first car, 440 for two, +200 for each extra one (with the example values)
  covered_cars integer := coalesce((p_inputs ->> 'covered_parking_cars')::integer, 0);
  uncovered_cars integer := coalesce((p_inputs ->> 'uncovered_parking_cars')::integer, 0);
begin
  select * into pl from core.price_lists where id = p_price_list_id;
  if not found then
    raise exception 'unknown price list %', p_price_list_id using errcode = 'CX004';
  end if;
  if covered_cars < 0 or uncovered_cars < 0 then
    raise exception 'cars cannot be negative' using errcode = 'CX004';
  end if;

  covered_sqft := 0;
  uncovered_sqft := 0;

  if client_type = 'home' then
    if coalesce((p_inputs ->> 'bedrooms')::integer, -1) < 0 then
      raise exception 'bedrooms is required for a home' using errcode = 'CX004';
    end if;
    covered_sqft := pl.home_base_sqft + (p_inputs ->> 'bedrooms')::integer * pl.home_bedroom_sqft;
  elsif client_type = 'business' then
    if coalesce((p_inputs ->> 'covered_sqft')::numeric, -1) < 0 then
      raise exception 'covered_sqft is required for a business' using errcode = 'CX004';
    end if;
    covered_sqft := (p_inputs ->> 'covered_sqft')::numeric;
  else
    raise exception 'client_type must be home or business' using errcode = 'CX004';
  end if;

  if covered_cars > 0 then
    covered_sqft := covered_sqft + pl.parking_first_car_sqft + (covered_cars - 1) * pl.parking_extra_car_sqft;
  end if;
  if uncovered_cars > 0 then
    uncovered_sqft := uncovered_sqft + pl.parking_first_car_sqft + (uncovered_cars - 1) * pl.parking_extra_car_sqft;
  end if;

  for area in select jsonb_array_elements(coalesce(p_inputs -> 'extra_areas', '[]'::jsonb))
  loop
    if area ? 'sqft' then
      area_sqft := (area ->> 'sqft')::numeric;
    elsif area ? 'sqm' then
      area_sqft := (area ->> 'sqm')::numeric * pl.sqm_to_sqft;
    elsif area ? 'paces_long' and area ? 'paces_wide' then
      area_sqft := ((area ->> 'paces_long')::numeric * pl.pace_to_ft) * ((area ->> 'paces_wide')::numeric * pl.pace_to_ft);
    else
      raise exception 'extra area needs sqft, sqm or paces' using errcode = 'CX004';
    end if;
    if area_sqft < 0 then
      raise exception 'area cannot be negative' using errcode = 'CX004';
    end if;
    -- Never assumed: the prompt requires asking whether the area has a roof.
    if jsonb_typeof(area -> 'covered') is distinct from 'boolean' then
      raise exception 'extra area must say whether it is covered' using errcode = 'CX004';
    end if;
    if (area ->> 'covered')::boolean then
      covered_sqft := covered_sqft + area_sqft;
    else
      uncovered_sqft := uncovered_sqft + area_sqft;
    end if;
  end loop;
end;
$$;

create table core.quotes (
  id bigint generated by default as identity primary key,
  brand_id bigint not null references core.brands (id),
  deal_id bigint not null references public.deals (id) on delete restrict,
  version integer not null check (version > 0),
  price_list_id bigint not null references core.price_lists (id),
  price_confirmed boolean not null, -- snapshot: was the price list confirmed when quoting?
  covered_sqft numeric(12, 2) not null check (covered_sqft >= 0),
  uncovered_sqft numeric(12, 2) not null check (uncovered_sqft >= 0),
  subtotal numeric(12, 2) not null,
  discount numeric(12, 2) not null,
  total numeric(12, 2) not null,
  min_applied boolean not null,
  currency text not null,
  inputs jsonb not null,
  valid_until date,
  status text not null default 'sent' check (status in ('sent', 'accepted', 'superseded')),
  created_at timestamptz not null default now(),
  unique (deal_id, version)
);

-- Amounts are always recalculated here, whatever the caller sends. Nothing outside this
-- database can write a total: not the bot, not core-api.
create function core.quotes_before_insert() returns trigger
  language plpgsql
  set search_path = ''
  as $$
declare
  deal_brand_id bigint;
  pl core.price_lists;
  totals record;
begin
  select brand_id into deal_brand_id from public.deals where id = new.deal_id for update;
  if not found then
    raise exception 'unknown deal %', new.deal_id using errcode = 'CX004';
  end if;
  new.brand_id := deal_brand_id;

  new.price_list_id := coalesce(new.price_list_id, core.active_price_list(new.brand_id));
  select * into pl from core.price_lists where id = new.price_list_id and brand_id = new.brand_id;
  if not found then
    raise exception 'no price list for this brand' using errcode = 'CX004';
  end if;

  select * into totals from core.quote_totals(pl.id, new.covered_sqft, new.uncovered_sqft);
  new.subtotal := totals.subtotal;
  new.discount := totals.discount;
  new.total := totals.total;
  new.min_applied := totals.min_applied;
  new.currency := pl.currency;
  new.price_confirmed := pl.is_confirmed;

  -- The row lock on the deal above serializes this count.
  select coalesce(max(version), 0) + 1 into new.version from core.quotes where deal_id = new.deal_id;
  return new;
end;
$$;
create trigger quotes_before_insert before insert on core.quotes
  for each row execute function core.quotes_before_insert();

create function core.quotes_guard() returns trigger
  language plpgsql
  set search_path = ''
  as $$
begin
  if tg_op = 'DELETE' then
    raise exception 'quotes cannot be deleted' using errcode = 'CX001';
  end if;
  if (to_jsonb(new) - 'status' - 'valid_until') is distinct from (to_jsonb(old) - 'status' - 'valid_until') then
